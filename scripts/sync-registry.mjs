import { Buffer } from 'node:buffer'
import { readFile } from 'node:fs/promises'
import { extname, posix } from 'node:path'
import { resolveRegistryItems } from '../packages/cli/src/index.ts'
import { registryProfiles } from '../packages/registry/src/index.ts'
import { projectFiles, registryItems, registryRoot, relocateModuleSpecifier, rewriteModuleSpecifiers, rewriteSourceModuleSpecifiers } from './registry-artifacts.mjs'

const check = process.argv.includes('--check')
if (process.argv.slice(2).some(arg => arg !== '--check')) { throw new Error('Usage: node scripts/sync-registry.mjs [--check]') }
const items = await registryItems()
const baseItems = items.filter(item => item.type === 'component' && !item.name.startsWith('agent-'))
const outputs = new Map()
function output(path, content) {
  const prior = outputs.get(path)
  if (prior !== undefined && !Buffer.from(prior).equals(Buffer.from(content))) {
    throw new Error(`Conflicting generated owners for ${path}`)
  }
  outputs.set(path, content)
}

async function sourcePlan(names, target) {
  const plan = await resolveRegistryItems(names, { registryRoot, registryFormat: 'canonical', target })
  const destinations = new Set()
  for (const file of plan.files) {
    if (destinations.has(file.to)) { throw new Error(`Duplicate Registry source owner: ${target}:${file.to}`) }
    destinations.add(file.to)
  }
  return plan
}

// Native npm delivery is the same SFC/lib/style tree installed by the CLI.
const nativeItems = baseItems.filter(item => item.targets.includes('weapp'))
const native = await sourcePlan(nativeItems.map(item => item.id), 'weapp')
const primaryExports = new Map(nativeItems.map((item) => {
  const primary = item.files.find(file => file.target === 'weapp' && file.to.endsWith('.vue'))
  if (!primary || !item.exportName) { throw new Error(`Missing native component export: ${item.id}`) }
  return [primary.to, item.exportName]
}))
const nativeExports = []
for (const file of native.files) {
  const path = `packages/ui-weapp/native/${file.to}`
  output(path, await readFile(file.sourcePath))
  if (file.to.startsWith('src/components/ui/') && file.to.endsWith('.vue')) {
    const name = primaryExports.get(file.to) ?? posix.basename(file.to, '.vue').split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('')
    nativeExports.push(`export { default as ${name} } from './${file.to.slice('src/'.length)}'`)
  }
}
output('packages/ui-weapp/native/src/index.ts', `// Generated by scripts/sync-registry.mjs from Registry native SFCs.\n${nativeExports.sort().join('\n')}\n`)

// H5 keeps its existing public file layout; only import specifiers are relocated.
const h5 = await sourcePlan(baseItems.filter(item => item.targets.includes('h5')).map(item => item.id), 'h5')
function h5Destination(path) {
  return path.startsWith('src/components/ui/')
    ? path.replace('src/components/ui/', 'packages/ui-h5/src/')
    : `packages/ui-h5/${path}`
}
const h5Files = new Map(h5.files.map(file => [file.to, h5Destination(file.to)]))
for (const file of h5.files) {
  if (file.to === 'src/lib/varo-primitives.ts') { continue }
  const destination = h5Destination(file.to)
  let source = await readFile(file.sourcePath, 'utf8')
  if (extname(file.to) === '.ts') {
    source = rewriteModuleSpecifiers(source, file.to, (specifier) => {
      if (!specifier.startsWith('.')) { return specifier }
      const original = posix.normalize(posix.join(posix.dirname(file.to), specifier))
      if (original === 'src/lib/varo-primitives') { return '@varo/primitives-h5' }
      const extension = ['', '.ts', '.vue', '.css'].find(suffix => h5Files.has(original + suffix))
      if (extension === undefined) { throw new Error(`${file.from}: import is not owned by its Registry closure: ${specifier}`) }
      const mapped = h5Files.get(original + extension)
      let next = posix.relative(posix.dirname(destination), mapped)
      if (extension && next.endsWith(extension)) { next = next.slice(0, -extension.length) }
      return next.startsWith('.') ? next : `./${next}`
    })
    source = `// Generated from ${file.from}; edit the Registry source.\n${source}`
  }
  output(destination, source)
}

